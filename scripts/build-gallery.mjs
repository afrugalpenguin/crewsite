// Builds gallery/thumbs/<name>.jpg (480x270) for any screenshot missing one, removes orphan thumbs,
// and writes gallery/manifest.js for index.html. Run by .github/workflows/gallery.yml, or `npm run gallery`.
import { readdir, rm, writeFile, mkdir } from 'node:fs/promises';
import sharp from 'sharp';

const DIR = 'gallery';
const THUMBS = `${DIR}/thumbs`;
const IMAGE = /\.(jpe?g|png|webp)$/i;
const thumbOf = (name) => name.replace(/\.\w+$/, '.jpg');

// WoW screenshot names carry MMDDYY; sort those as YYMMDD, oldest first. Undated files follow, alphabetically.
function sortKey(name) {
  const m = /_(\d\d)(\d\d)(\d\d)_/.exec(name);
  return m ? '0' + m[3] + m[1] + m[2] + name : '1' + name.toLowerCase();
}

await mkdir(THUMBS, { recursive: true });
const shots = (await readdir(DIR, { withFileTypes: true }))
  .filter((e) => e.isFile() && IMAGE.test(e.name))
  .map((e) => e.name)
  .sort((a, b) => (sortKey(a) < sortKey(b) ? -1 : 1));

const wanted = new Set(shots.map(thumbOf));
const existing = new Set(await readdir(THUMBS));

for (const name of shots) {
  if (existing.has(thumbOf(name))) continue;
  await sharp(`${DIR}/${name}`).resize(480, 270, { fit: 'cover' }).jpeg({ quality: 80 }).toFile(`${THUMBS}/${thumbOf(name)}`);
  console.log('thumb +', thumbOf(name));
}
for (const name of existing) {
  if (wanted.has(name)) continue;
  await rm(`${THUMBS}/${name}`);
  console.log('thumb -', name);
}

await writeFile(`${DIR}/manifest.js`, '// Generated by scripts/build-gallery.mjs. Do not edit.\nwindow.GALLERY = ' + JSON.stringify(shots, null, 2) + ';\n');
console.log(`manifest: ${shots.length} screenshots`);
